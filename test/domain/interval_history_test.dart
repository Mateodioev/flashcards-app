import 'package:flashcards2/domain/enums.dart';
import 'package:flashcards2/domain/scheduling/fsrs5.dart';
import 'package:flashcards2/domain/scheduling/scheduler.dart';
import 'package:flutter_test/flutter_test.dart';

import '../support/canonical_vectors.dart';

/// Reproduces the canonical FSRS-6 **interval-history** vector.
///
/// This is the vector that the pure memory math cannot produce: it depends on
/// sub-day learning steps and a persisted step index. It runs through the
/// domain `Scheduler` with the FSRS-6 adapter as its engine (fuzzing off,
/// the library default), so it gates the whole integration, not just the
/// engine.
///
/// The vector was generated by the raw reference algorithm (21-parameter
/// FSRS-6 defaults; reproduced by `package:fsrs 2.0.1` in the Phase 1
/// spike, docs/fsrs6_migration_plan.md), which graduates a card on the
/// first successful learning review, so it maps to
/// [SchedulerConfig.singleStep]. Anki-style two-step scheduling is exercised
/// separately in `learning_steps_test.dart` — it changes this sequence by
/// design and must not be smuggled into this gate. Phase 4 of the migration
/// plan re-derives it from fsrs-rs/py-fsrs with repo+commit provenance.
void main() {
  final scheduler = Scheduler();

  test('interval history matches the canonical FSRS-6 vector', () {
    var card = const CardSchedule.newCard();
    var now = DateTime.utc(2022, 11, 29, 12, 30);
    final actual = <int>[];

    for (final rating in fsrs6CanonicalRatings) {
      final outcome = scheduler.review(card: card, rating: rating, now: now);
      card = outcome.schedule;
      actual.add(outcome.scheduledDays);
      now = card.due!;
    }

    expect(actual, fsrs6CanonicalIntervals);
  });

  test('ROLLBACK GATE: Fsrs5Scheduler through the Scheduler seam still '
      'reproduces the FSRS-5 vector', () {
    // The migration's rollback contract (docs/fsrs6_migration_plan.md,
    // Phase 6) claims rollback is a config swap. This proves it through the
    // integration seam — the frozen engine wired into SchedulerConfig —
    // not just through the engine in isolation (that is what
    // fsrs5_reference_vectors_test covers). Native review advisory
    // R3-rollback-contract-untested.
    final rollback = Scheduler(
      SchedulerConfig(memoryEngine: const Fsrs5Scheduler()),
    );

    var card = const CardSchedule.newCard();
    var now = DateTime.utc(2022, 11, 29, 12, 30);
    final actual = <int>[];
    for (final rating in fsrs6CanonicalRatings) {
      final outcome = rollback.review(card: card, rating: rating, now: now);
      card = outcome.schedule;
      actual.add(outcome.scheduledDays);
      now = card.due!;
    }

    expect(actual, fsrs5CanonicalIntervals);
  });

  test('a new card with Easy graduates immediately', () {
    final outcome = scheduler.review(
      card: const CardSchedule.newCard(),
      rating: Rating.easy,
      now: DateTime.utc(2022, 11, 29),
    );
    expect(outcome.schedule.state, ReviewState.review);
    // FSRS-6 defaults: initial stability for Easy is w3 = 16.1507.
    expect(outcome.schedule.memory!.stability, closeTo(16.1507, 1e-4));
    expect(outcome.scheduledDays, 16);
  });

  test('a new card with Good enters learning, not review', () {
    final outcome = scheduler.review(
      card: const CardSchedule.newCard(),
      rating: Rating.good,
      now: DateTime.utc(2022, 11, 29),
    );
    expect(outcome.schedule.state, ReviewState.learning);
    expect(outcome.scheduledDays, 0);
    expect(outcome.schedule.step, 0);
  });

  test('a lapse increments lapses and enters relearning', () {
    // Six Goods to reach a graduated review card, then Again.
    var card = const CardSchedule.newCard();
    var now = DateTime.utc(2022, 11, 29, 12, 30);
    for (var i = 0; i < 6; i++) {
      card = scheduler
          .review(card: card, rating: Rating.good, now: now)
          .schedule;
      now = card.due!;
    }
    expect(card.state, ReviewState.review);
    expect(card.lapses, 0);

    final lapsed = scheduler.review(card: card, rating: Rating.again, now: now);
    expect(lapsed.schedule.state, ReviewState.relearning);
    expect(lapsed.schedule.lapses, 1);
    expect(lapsed.scheduledDays, 0);
  });

  test('same-day reviews floor elapsed days to zero', () {
    // Local-time construction keeps this independent of the runner's zone,
    // unlike the UTC-based vector tests above.
    final t0 = DateTime(2022, 11, 29, 12, 30);
    expect(Scheduler.elapsedDays(t0, t0.add(const Duration(minutes: 1))), 0);
    expect(Scheduler.elapsedDays(t0, t0.add(const Duration(hours: 4))), 0);
    expect(Scheduler.elapsedDays(t0, t0.add(const Duration(days: 4))), 4);
  });
}
